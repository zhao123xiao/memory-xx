  docker compose --profile full --profile dev up -d --remove-orphans --build
else
  docker compose --profile full --profile dev up -d --remove-orphans
fi

ADMIN_TOKEN="$(
  docker compose exec -T memory-xx sh -lc 'printf "%s" "$MEMORY_XX_ADMIN_TOKEN"'
)"
ADMIN_ENV=("MEMORY_XX_ADMIN_TOKEN=$ADMIN_TOKEN")
FUNCTIONAL_AUTH_ENV=(
  "MEMORY_XX_API_TOKEN=$ADMIN_TOKEN"
  "MEMORY_XX_ADMIN_TOKEN=$ADMIN_TOKEN"
)

env "${ADMIN_ENV[@]}" TMPDIR="${TMPDIR:-/tmp}" \
  npm run smoke:compose-profile-live -- \
    --url "http://127.0.0.1:${MEMORY_XX_WRAPPER_HOST_PORT}/health" \
    --wait-ms "$MEMORY_XX_COMPOSE_FULL_WAIT_MS"

if [[ "$MEMORY_XX_COMPOSE_FULL_SKIP_FUNCTIONAL" == "1" ]]; then
  echo "Skipping functional smoke because MEMORY_XX_COMPOSE_FULL_SKIP_FUNCTIONAL=1"
  exit 0
fi

