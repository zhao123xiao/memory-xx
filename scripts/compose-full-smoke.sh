: "${MEMORY_XX_RERANKER_DOWNSTREAM_URL:=http://memory-xx-dev-reranker-upstream:8084/v3/rerank}"
: "${MEMORY_XX_RERANKER_DOWNSTREAM_MODELS_URL:=http://memory-xx-dev-reranker-upstream:8084/v3/models}"
: "${MEMORY_XX_LLM_UPSTREAM_HEALTH_URL:=http://memory-xx-dev-chat-upstream:5223/health}"
: "${MEMORY_INTELLIGENCE_BASE_URL:=http://memory-xx-dev-chat-upstream:5223/v1}"

: "${MEMORY_XX_WRAPPER_HOST_PORT:=15100}"
: "${MEMORY_XX_EMBEDDING_PROXY_HOST_PORT:=15221}"
